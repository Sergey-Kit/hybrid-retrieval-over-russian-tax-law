def _clause_text(articles: dict[str, Article], article: str, clause: str | None) -> str | None:
    found = articles.get(article)
    if found is None:
        return None
    if clause is None:
        return found.text
    for item in found.clauses:
        if item.number == clause:
            return item.text
    return None


def verify(articles: list[Article]) -> list[str]:
    """Проверить каждую запись против корпуса. Пустой список — всё сходится."""
    by_number = {a.number: a for a in articles}
    problems: list[str] = []
    for question in QUESTIONS:
        text = _clause_text(by_number, question.article, question.clause)
        if text is None:
            problems.append(f"{question.norm_unit_id}: норма не найдена в корпусе")
            continue
        if question.anchor.lower() not in re.sub(r"\s+", " ", text).lower():
            problems.append(
                f"{question.norm_unit_id}: опорная подстрока не найдена — {question.anchor!r}"
            )
    return problems


def build_layer1_pairs(articles: list[Article]) -> list[SilverPair]:
    """Две пары на вопрос: с лексическим якорем и без него, эталон общий.

    Обе формулировки получают один `cluster_id`, чтобы всегда попадать в один
    сплит: иначе сравнение «якорь против живого языка» пойдёт по разным запросам
    и потеряет смысл.
    """
    problems = verify(articles)
    if problems:
        raise ValueError("набор слоя 1 не сходится с корпусом:\n  " + "\n  ".join(problems))

    pairs: list[SilverPair] = []
    for index, question in enumerate(QUESTIONS):
        gold_norms = (question.norm_unit_id,) + question.extra_gold
        gold_articles = tuple(
            dict.fromkeys((question.article_id,) + tuple(g.split("/p")[0] for g in question.extra_gold))
        )
        cluster = f"layer1/{question.question_type}/{question.article}/{question.clause}"
        for suffix, query, query_type in (
            ("demand", question.demand_excerpt, QUERY_TYPE_LEXICAL),
            ("natural", question.natural, QUERY_TYPE_NATURAL),
        ):
            pairs.append(
                SilverPair(
                    query_id=f"l1-{index:02d}-{suffix}",
                    query=query,
                    gold_norm_ids=gold_norms,
                    gold_article_ids=gold_articles,
                    query_type=query_type,
                    source=SOURCE_LAYER1,
                    source_id=f"{question.question_type}/{question.norm_unit_id}",
                    cluster_id=cluster,
                )
            )
    return pairs
