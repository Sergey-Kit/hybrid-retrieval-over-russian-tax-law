@dataclass(frozen=True)
class Layer1Question:
    """Один вопрос слоя 1 в двух формулировках, с проверяемой привязкой к норме."""

    question_type: str
    article: str
    clause: str | None
    #: Подстрока, которая обязана быть в тексте этого пункта. Доказательство того,
    #: что норма действительно говорит то, что мы ей приписываем.
    anchor: str
    #: Формулировка с лексическим якорем — как в тексте требования.
    demand_excerpt: str
    #: Живой вопрос без номера статьи — как спросит бухгалтер.
    natural: str
    #: Дополнительные нормы эталона (например, ст. 6.1 для любого срока).
    extra_gold: tuple[str, ...] = ()

    @property
    def article_id(self) -> str:
        return f"nk1/st{self.article}"

    @property
    def norm_unit_id(self) -> str:
        return f"{self.article_id}/p{self.clause}" if self.clause else self.article_id


