"""Синтетический набор слоя 1: вопросы про само требование ФНС.

Зачем он нужен. Silver set из решений и писем — 1678 пар — покрывает всё
налоговое право, а первая версия продукта обслуживает узкий процедурный срез:
какой это тип требования, какой срок ответа, что обязаны представить, что вне
предмета, что за неответ. Статьи слоя 1 задевают лишь 52 пары из 1678 (3%), в
тестовом сплите — 8 из 337, а по ст. 6.1, которая задаёт исчисление любого
срока, запросов ноль. Померить на этом продукт нельзя.

Почему набор вообще можно построить без юриста. Слой 1 выбран продуктовым
решением именно потому, что у его вопросов **есть проверяемый правильный
ответ**: срок написан в пункте, состав обязанности написан в пункте, санкция —
в статье 126. Эталон известен по построению.

Как устроена защита от выдумывания. Каждая запись указывает не только норму, но
и **опорную подстроку**, которая обязана присутствовать в тексте этого пункта.
Проверка идёт против разобранного корпуса, а не против памяти автора: если
формулировка нормы изменится или пункт переедет, запись упадёт на тесте, а не
продолжит тихо возвращать неверный эталон.

Два входа продукта — две формулировки. Требование ФНС само ссылается на статью
(«на основании пункта 3 статьи 93»), то есть лексический якорь в нём есть.
Живой вопрос бухгалтера якоря не имеет. Обе формулировки указывают на одну и ту
же норму, и это позволяет измерить **ровно то, что теряется на живом языке**.

Честное ограничение: набор порождён тем же, кто строит индекс, поэтому меряет
структурную достижимость нормы, а не языковой разрыв между тем, как спрашивает
пользователь, и тем, как написан закон. Он не заменяет golden set из P4.
"""
