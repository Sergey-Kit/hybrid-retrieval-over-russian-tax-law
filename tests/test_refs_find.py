"""Разбор ссылок на нормы: надстройка P4 над нормализатором P3.

Случаи взяты из реальных требований пилота."""
import pytest

from p3.refs.find import find, parse_cell


@pytest.mark.parametrize("text,expected", [
    ("НК ст.93.1 п.2; НК ст.126 п.2", ["nk1/st93.1/p2", "nk1/st126/p2"]),
    ("НК ст. 93; НК ст. 80", ["nk1/st93", "nk1/st80"]),
    # Порядок слов в юридическом тексте обратный сокращённой записи.
    ("подпунктом 2 пункта 1 статьи 31", ["nk1/st31/p1/sp2"]),
    ("п. 8.1 ст. 88", ["nk1/st88/p8.1"]),
    ("ст. 76 п. 3 пп. 2", ["nk1/st76/p3/sp2"]),
    # Точка внутри номера статьи не отделяет пункт.
    ("НК ст.129.1", ["nk1/st129.1"]),
    ("НК ст.169", ["nk2/st169"]),
])
def test_parse_cell(text, expected):
    assert [r.unit_id for r in parse_cell(text)] == expected


def test_quantifier_belongs_to_nearest_article():
    """«ст. 129.1» не должна наследовать пункт от предыдущей статьи."""
    text = "В соответствии с пунктом 5 статьи 93.1 НК РФ, а также ст. 129.1 сообщаем"
    assert [r.unit_id for r in find(text)] == ["nk1/st93.1/p5", "nk1/st129.1"]


def test_neighbouring_articles_keep_own_clauses():
    text = "штраф по ст. 126 п. 2, приостановление по ст. 76 п. 3 пп. 2"
    assert [r.unit_id for r in find(text)] == ["nk1/st126/p2", "nk1/st76/p3/sp2"]


def test_enumeration_of_clauses_on_one_article():
    """«пунктом 2, абзацем вторым пункта 5 статьи 93.1» — две нормы, не одна.

    Нормализатор P3 обрывает цепочку квалификаторов на втором «пункте» и
    оставляет только п. 5. Пропуск п. 2 подменяет основание: п. 1 — встречное
    истребование в рамках проверки, п. 2 — вне проверки по конкретной сделке.
    """
    text = ("В соответствии с пунктом 2, абзацем вторым пункта 5 статьи 93.1 "
            "Налогового кодекса Российской Федерации необходимо представить")
    assert {r.unit_id for r in find(text)} == {"nk1/st93.1/p2", "nk1/st93.1/p5/a2"}


def test_other_codes_are_dropped():
    """КоАП разбирается нормализатором P3 как отдельный кодекс и сюда не попадает."""
    text = ("влечет ответственность, предусмотренную частью 1 статьи 15.6 Кодекса "
            "Российской Федерации об административных правонарушениях")
    assert find(text) == []


def test_official_gazette_is_not_a_norm():
    text = "Собрание законодательства Российской Федерации, 07.01.2002, N 1 (ч. 1), ст. 1"
    assert find(text) == []


def test_paragraph_is_kept():
    """«абзацем первым пункта 5» — уровень абзаца различает редакции нормы."""
    text = "абзацем первым пункта 5 статьи 93.1 Налогового кодекса"
    assert [r.unit_id for r in find(text)] == ["nk1/st93.1/p5/a1"]
